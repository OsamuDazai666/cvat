"""Render functions/<name>/function.yaml for every canopy function (re-run after classes.json changes).

    python functions/gen.py
Host paths use Docker Desktop's daemon-side form (/run/desktop/mnt/host/<drive>/...), because nuctl asks the
daemon to bind them from inside a Linux container.
"""
import json
import os
from pathlib import Path

import specs

HERE = Path(__file__).resolve().parent


def host(p):
    p = p.replace("\\", "/")
    return f"/run/desktop/mnt/host/{p[0].lower()}{p[2:]}"


# Windows paths of the mounted folders (gen.py also runs inside the tools container, where they are /work/...)
CVAT_DIR = os.environ.get("CANOPY_CVAT_HOST_DIR", "D:/canopy-cvat/cvat/canopy")      # this canopy/ folder
TOOLS_DIR = os.environ.get("CANOPY_TOOLS_HOST_DIR", "D:/canopy-evidence/tools")
VOLUMES = [("canopy-fn-common", host(CVAT_DIR + "/functions/common"), "/opt/canopy_fn"),
           ("canopy-tools", host(TOOLS_DIR), "/canopy/tools")]

FUNCS = {
    "sam3-interactor": dict(kind="interactor", title="SAM 3 (canopy)", timeout="60s", workers=2,
                            desc="SAM 3 masks from clicks / a box (model in canopy-models)",
                            extra={"min_pos_points": 0, "min_neg_points": 0, "startswith_box_optional": "true",
                                   "help_message": "SAM 3: positive/negative clicks, optionally start with a box"}),
    "canopy-vehicles": dict(kind="detector", title="Canopy vehicles (SAM 3 + Qwen)", timeout="600s", workers=1,
                            desc="SAM 3 proposals + Qwen closed-set class (auto_v1 recipe)",
                            labels=specs.vehicles()),
    "plate-reader": dict(kind="detector", title="Canopy plates (detector + Qwen)", timeout="300s", workers=1,
                         desc="plate_det_v1 boxes + Qwen3.8 reads number, code, origin, category, colour, layout",
                         labels=specs.plates()),
}


def q(s):
    return json.dumps(str(s))


def render(name, f):
    ann = [f"    name: {q(f['title'])}", f"    type: {f['kind']}", "    version: 2" if f["kind"] == "interactor" else None]
    ann = [a for a in ann if a]
    if "labels" in f:
        spec = json.dumps(specs.nuclio_spec(f["labels"]), indent=1)
        ann.append("    spec: |\n" + "\n".join("      " + l for l in spec.splitlines()))
    else:
        ann.append("    spec:")
    for k, v in f.get("extra", {}).items():
        ann.append(f"    {k}: {q(v)}")
    vols = "\n".join(
        f"    - volume:\n        name: {n}\n        hostPath:\n          path: {q(hp)}\n"
        f"      volumeMount:\n        name: {n}\n        mountPath: {mp}\n        readOnly: true"
        for n, hp, mp in VOLUMES)
    return f"""# generated by functions/gen.py — edit gen.py/specs.py instead
metadata:
  name: canopy-{name.removeprefix('canopy-')}
  namespace: cvat
  annotations:
{chr(10).join(ann)}

spec:
  description: {q(f['desc'])}
  runtime: 'python:3.12'
  handler: main:handler
  eventTimeout: {f['timeout']}
  env:
    - name: PYTHONPATH
      value: /opt/nuclio:/opt/canopy_fn
  build:
    image: canopy-cvat/fn-{name}:latest
    baseImage: canopy-cvat/fn-base:latest
    directives:
      preCopy:
        - kind: WORKDIR
          value: /opt/nuclio
  volumes:
{vols}
  triggers:
    myHttpTrigger:
      numWorkers: {f['workers']}
      kind: http
      workerAvailabilityTimeoutMilliseconds: 10000
      attributes:
        maxRequestBodySize: 67108864
  platform:
    attributes:
      restartPolicy:
        name: always
        maximumRetryCount: 3
      mountMode: volume
"""


if __name__ == "__main__":
    for name, f in FUNCS.items():
        (HERE / name).mkdir(exist_ok=True)
        (HERE / name / "function.yaml").write_text(render(name, f), encoding="utf-8", newline="\n")
        print("wrote", name)
